#!/usr/bin/env node
// Regenerates src/lib/generated/college-teams.generated.ts from ESPN: every men's
// Division I basketball program (group 50) and which of them play FBS (group 80)
// or FCS (group 81) football. Nothing reads this at runtime: the output is
// committed, so parsing makes no network call and no DB read.
//
//   node scripts/generate-college-teams.mjs [--basketball-season 2027] [--football-season 2026]
//
// Rerun once a year, or when a conference realignment moves a program in or out
// of Division I, then review the diff. It refuses to write a list that shrank by
// more than a handful of teams, which is what a partial ESPN response looks like.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = resolve(ROOT, "src/lib/generated/college-teams.generated.ts");
const CORE = "https://sports.core.api.espn.com/v2/sports";
const SITE = "https://site.api.espn.com/apis/site/v2/sports";
const MAX_SHRINK = 5;

function argValue(name, fallback) {
  const i = process.argv.indexOf("--" + name);
  return i >= 0 ? process.argv[i + 1] : fallback;
}
const basketballSeason = argValue("basketball-season", "2027");
const footballSeason = argValue("football-season", "2026");

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  return res.json();
}

// The core API's group listing is the complete one: the site API's /groups tree
// stops at 25 conferences (289 teams when this was written).
async function groupTeamIds(sportPath, season, group) {
  const url = `${CORE}/${sportPath}/seasons/${season}/types/2/groups/${group}/teams?limit=1000`;
  const body = await getJson(url);
  if (body.pageCount !== 1) throw new Error(`expected one page for group ${group}, got ${body.pageCount}`);
  const ids = body.items.map((item) => {
    const m = /\/teams\/(\d+)/.exec(item.$ref);
    if (!m) throw new Error("unreadable team ref " + item.$ref);
    return m[1];
  });
  if (ids.length !== body.count) throw new Error(`group ${group}: read ${ids.length} of ${body.count}`);
  return ids;
}

function pickFields(team) {
  return {
    id: String(team.id),
    name: team.displayName,
    location: team.location,
    short: team.shortDisplayName,
    mascot: team.name,
  };
}

async function main() {
  const [d1Ids, fbsIds, fcsIds, siteList] = await Promise.all([
    groupTeamIds("basketball/leagues/mens-college-basketball", basketballSeason, 50),
    groupTeamIds("football/leagues/college-football", footballSeason, 80),
    groupTeamIds("football/leagues/college-football", footballSeason, 81),
    getJson(`${SITE}/basketball/mens-college-basketball/teams?limit=1000`),
  ]);
  const fbs = new Set(fbsIds);
  const fcs = new Set(fcsIds);
  const siteById = new Map(siteList.sports[0].leagues[0].teams.map(({ team }) => [String(team.id), team]));

  const teams = [];
  for (const id of d1Ids) {
    // A team the site list leaves out (a program new to D1) is read on its own.
    const team =
      siteById.get(id) ?? (await getJson(`${CORE}/basketball/leagues/mens-college-basketball/seasons/${basketballSeason}/teams/${id}`));
    const fields = pickFields(team);
    if (!fields.name || !fields.location) throw new Error("team without a name or location: " + id);
    teams.push({ ...fields, football: fbs.has(id) ? "FBS" : fcs.has(id) ? "FCS" : null });
  }
  teams.sort((a, b) => a.name.localeCompare(b.name));

  if (existsSync(OUTPUT)) {
    const previous = (readFileSync(OUTPUT, "utf8").match(/\bid: "/g) ?? []).length;
    if (teams.length < previous - MAX_SHRINK) {
      throw new Error(`refusing to shrink the list from ${previous} to ${teams.length}; check ESPN, then delete the file to force`);
    }
  }

  const rows = teams
    .map(
      (t) =>
        `  { id: ${JSON.stringify(t.id)}, name: ${JSON.stringify(t.name)}, location: ${JSON.stringify(t.location)}, short: ${JSON.stringify(t.short)}, mascot: ${JSON.stringify(t.mascot)}, football: ${JSON.stringify(t.football)} },`
    )
    .join("\n");
  const body = `// GENERATED by scripts/generate-college-teams.mjs. Do not edit by hand: rerun it.
// Source: ESPN men's college basketball group 50 (season ${basketballSeason}), college football
// groups 80 (FBS) and 81 (FCS) (season ${footballSeason}). \`football\` is matched by ESPN team id.
export type GeneratedCollegeTeam = {
  id: string;
  name: string;
  location: string;
  short: string;
  mascot: string;
  football: "FBS" | "FCS" | null;
};

export const NCAAB_D1_TEAMS: GeneratedCollegeTeam[] = [
${rows}
];
`;
  mkdirSync(dirname(OUTPUT), { recursive: true });
  writeFileSync(OUTPUT, body);
  const count = (kind) => teams.filter((t) => t.football === kind).length;
  console.log(`wrote ${teams.length} teams: ${count("FBS")} FBS, ${count("FCS")} FCS, ${count(null)} basketball-only`);
  console.log(`football groups: ${fbs.size} FBS, ${fcs.size} FCS`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
