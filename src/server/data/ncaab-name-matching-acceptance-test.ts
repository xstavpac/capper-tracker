// For EVERY ESPN "<X> State ..." school, its bare "<X> ..." sibling (when one exists) is a different team.
const siblingMerges: string[] = [];
for (const e of espn) {
  const m = /^(.*) State (.*)$/.exec(e);
  if (!m) continue;
  for (const other of espn) if (other.startsWith(m[1] + " ") && other !== e && teamNamesMatch(e, other, NCAAB)) siblingMerges.push(e + " ~ " + other);
}
expect("no '<X> State' school matches an '<X> ...' school", siblingMerges, []);
// "St" / "St." in other positions and "Saint" are not touched.
expect("St. John's matches St John's (period fold, unchanged)", teamNamesMatch("St. John's Red Storm", "St John's Red Storm", NCAAB), true);
expect("St. Bonaventure matches St Bonaventure", teamNamesMatch("St. Bonaventure Bonnies", "St Bonaventure Bonnies", NCAAB), true);
expect("Saint Mary's is NOT folded to St Mary's", teamNamesMatch("Saint Mary's Gaels", "St Mary's Gaels", NCAAB), false);
expect("St. John's does not match St. Joseph's", teamNamesMatch("St. John's Red Storm", "Saint Joseph's Hawks", NCAAB), false);
// teamNameEndsWith: nickname-vs-name, same fold, same boundaries.
expect("nickname 'cleveland state vikings' ends the card's 'Cleveland St Vikings'", teamNameEndsWith("Cleveland St Vikings", "cleveland state vikings", NCAAB), true);
expect("nickname 'michigan' does not end 'Michigan St Spartans'", teamNameEndsWith("Michigan St Spartans", "michigan", NCAAB), false);
expect("nickname 'kansas' does not end 'Kansas St Wildcats'", teamNameEndsWith("Kansas St Wildcats", "kansas", NCAAB), false);
expect("nickname 'ohio' does not end 'Ohio St Buckeyes'", teamNameEndsWith("Ohio St Buckeyes", "ohio", NCAAB), false);
expect("nickname 'washington state cougars' ends 'Washington St Cougars'", teamNameEndsWith("Washington St Cougars", "washington state cougars", NCAAB), true);
expect("nickname 'washington huskies' does not end 'Washington St Cougars'", teamNameEndsWith("Washington St Cougars", "washington huskies", NCAAB), false);
expect("nickname 'purdue fort wayne mastodons' ends 'Fort Wayne Mastodons' via the alias row", teamNameEndsWith("Fort Wayne Mastodons", "purdue fort wayne mastodons", NCAAB), true);

// ---- 4. every other league is byte-identical to before ---------------------------------------------

// The pre-change implementations, verbatim.
const LEGACY_ALIAS_LOOKUP: Record<string, Map<string, string>> = Object.fromEntries(
  Object.entries(CROSS_SOURCE_TEAM_ALIASES).map(([sportKey, rows]) => [
    sportKey,
    new Map(rows.map(([scoreFeed, oddsApi]) => [normalizeTeamName(scoreFeed), normalizeTeamName(oddsApi)])),
  ])
);
function legacyTeamNamesMatch(a: string, b: string, sportKey?: string): boolean {
  const na = normalizeTeamName(a);
  const nb = normalizeTeamName(b);
  if (na === nb) return true;
  const aliases = sportKey ? LEGACY_ALIAS_LOOKUP[sportKey] : undefined;
  if (!aliases) return false;
  return (aliases.get(na) ?? na) === (aliases.get(nb) ?? nb);
}
const foldText = (t: string) => normalizeTeamName(t).replace(/['’]/g, "");
function legacyEndsWith(teamName: string, nickname: string, sportKey?: string): boolean {
  const nick = foldText(nickname);
  if (!nick) return false;
  const rows = sportKey ? CROSS_SOURCE_TEAM_ALIASES[sportKey] : undefined;
  const row = rows?.find((r) => r.some((s) => normalizeTeamName(s) === normalizeTeamName(teamName)));
  return [teamName, ...(row ?? [])].some((spelling) => endsWithWholeWords(foldText(spelling), nick));
}
const OTHER_KEYS = ["americanfootball_nfl", "americanfootball_ncaaf", "basketball_nba", "basketball_wnba", "baseball_mlb", "icehockey_nhl", undefined];
const pool = [
  ...espn.filter((_, i) => i % 3 === 0),
  ...espn.filter((n) => /\bState\b/.test(n)),
  ...odds.filter((n) => / St /.test(n)).slice(0, 40),
  "Los Angeles Clippers", "LA Clippers", "Boston Celtics", "St Louis Blues", "St. Louis Cardinals", "Montréal Canadiens", "Montreal Canadiens",
  "Sam Houston Bearkats", "Sam Houston State Bearkats", "App State Mountaineers", "Appalachian State Mountaineers", "Youngstown State Penguins", "Youngstown St Penguins",
  "Ohio State Buckeyes", "Ohio St Buckeyes", "Penn State Nittany Lions", "Penn St Nittany Lions", "Kansas State Wildcats", "Kansas St Wildcats",
];
let namesDiffs = 0;
let endsDiffs = 0;
let comparisons = 0;
for (const key of OTHER_KEYS) {
  for (const a of pool) {
    for (const b of pool) {
      comparisons++;
      if (teamNamesMatch(a, b, key) !== legacyTeamNamesMatch(a, b, key)) namesDiffs++;
    }
    // nickname form: the lowercased full name, and its last two words
    const words = a.toLowerCase().split(/\s+/);
    for (const nick of [a.toLowerCase(), words.slice(-2).join(" "), words[words.length - 1]]) {
      for (const b of pool.slice(0, 60)) if (teamNameEndsWith(b, nick, key) !== legacyEndsWith(b, nick, key)) endsDiffs++;
    }
  }
}
console.log(`INFO: ${comparisons} name comparisons across ${OTHER_KEYS.length} non-NCAAB league keys`);
expect("teamNamesMatch: no result differs from the old code for any non-NCAAB league key", namesDiffs, 0);
expect("teamNameEndsWith: no result differs from the old code for any non-NCAAB league key", endsDiffs, 0);
expect("NCAAF still does not fold State/St (Ohio State vs Ohio St)", teamNamesMatch("Ohio State Buckeyes", "Ohio St Buckeyes", "americanfootball_ncaaf"), false);
expect("NFL/NBA/MLB/NHL/WNBA: 'State' names compare exactly", ["americanfootball_nfl", "basketball_nba", "baseball_mlb", "icehockey_nhl", "basketball_wnba"].map((k) => teamNamesMatch("Penn State Lions", "Penn St Lions", k)), [false, false, false, false, false]);
expect("no key: 'State' names compare exactly", teamNamesMatch("Penn State Lions", "Penn St Lions"), false);
expect("the NCAAF alias rows are unchanged (17 rows)", CROSS_SOURCE_TEAM_ALIASES.americanfootball_ncaaf.length, 17);
expect("the NBA alias rows are unchanged (1 row)", CROSS_SOURCE_TEAM_ALIASES.basketball_nba.length, 1);

// ---- 5. the five picks from 2026-11-03, through the real matchPicksToGame --------------------------

const T = (iso: string) => new Date(iso);
type Case = {
  school: string;
  // What the pick stores (ESPN spellings, as resolveScheduleGame returns them) and its bet text.
  pickHome: string; pickAway: string; detail: string; pickedSide: "HOME" | "AWAY"; line: number;
  // What the Live board card carries (The Odds API spellings).
  cardHome: string; cardAway: string;
  at: string;
};
const CASES: Case[] = [
  { school: "Purdue Fort Wayne +10", pickHome: "Duquesne Dukes", pickAway: "Purdue Fort Wayne Mastodons", detail: "Purdue Fort Wayne Mastodons +10", pickedSide: "AWAY", line: 10, cardHome: "Duquesne Dukes", cardAway: "Fort Wayne Mastodons", at: "2026-11-04T00:00:00Z" },
  { school: "Cleveland State +27", pickHome: "Missouri Tigers", pickAway: "Cleveland State Vikings", detail: "Cleveland State Vikings +27", pickedSide: "AWAY", line: 27, cardHome: "Missouri Tigers", cardAway: "Cleveland St Vikings", at: "2026-11-04T01:00:00Z" },
  { school: "Cal Baptist -10.5", pickHome: "California Baptist Lancers", pickAway: "North Florida Ospreys", detail: "California Baptist Lancers -10.5", pickedSide: "HOME", line: -10.5, cardHome: "Cal Baptist Lancers", cardAway: "North Florida Ospreys", at: "2026-11-04T03:00:00Z" },
  { school: "Hampton +14", pickHome: "Georgia Tech Yellow Jackets", pickAway: "Hampton Pirates", detail: "Hampton Pirates +14", pickedSide: "AWAY", line: 14, cardHome: "Georgia Tech Yellow Jackets", cardAway: "Hampton Pirates", at: "2026-11-04T00:00:00Z" },
  { school: "South Carolina -19.5", pickHome: "South Carolina Gamecocks", pickAway: "Stetson Hatters", detail: "South Carolina Gamecocks -19.5", pickedSide: "HOME", line: -19.5, cardHome: "South Carolina Gamecocks", cardAway: "Stetson Hatters", at: "2026-11-04T00:00:00Z" },
];
for (const c of CASES) {
  const gameTime = T(c.at);
  const pick = { homeTeam: c.pickHome, awayTeam: c.pickAway, betDetail: c.detail, gameTime };
  const card = { homeTeam: c.cardHome, awayTeam: c.cardAway, commenceTime: gameTime };
  expect(`${c.school}: attaches to its card (matchPicksToGame)`, matchPicksToGame([pick], card, "NCAAB").length, 1);
  // Never on a neighbour's card.
  const other = { homeTeam: "Duke Blue Devils", awayTeam: "Kentucky Wildcats", commenceTime: gameTime };
  expect(`${c.school}: not on an unrelated card`, matchPicksToGame([pick], other, "NCAAB").length, 0);
}
// The whole slate at once, through getPicksForGames' second pass: each pick lands on exactly its own card.
{
  const picks = CASES.map((c) => ({ homeTeam: c.pickHome, awayTeam: c.pickAway, betDetail: c.detail, gameTime: T(c.at), gameNumber: null }));
  const cards = CASES.map((c) => ({ homeTeam: c.cardHome, awayTeam: c.cardAway, commenceTime: T(c.at), gameNumber: null as number | null }));
  const perCard = assignPicksToNearestGame(cards.map((card) => matchPicksToGame(picks, card, "NCAAB")), cards);
  expect("the five-card slate: one pick per card, the right one", perCard.map((p) => p.map((x) => x.betDetail)), CASES.map((c) => [c.detail]));
}

// ---- 6. the same matcher everywhere else -----------------------------------------------------------

for (const c of CASES) {
  const gameTime = T(c.at);
  // live-scoreboard-ordering: ESPN-spelled score row -> Odds-spelled card (scores on cards).
  const score = { homeTeam: c.pickHome, awayTeam: c.pickAway, commenceTime: c.at, scores: [{ name: c.pickHome, score: "70" }, { name: c.pickAway, score: "60" }] };
  const hit = matchScoreToGame([score] as never, { homeTeam: c.cardHome, awayTeam: c.cardAway, commenceTime: c.at }, NCAAB);
  expect(`${c.school}: the card finds its live score (matchScoreToGame)`, hit !== undefined, true);
  expect(`${c.school}: both teams' scores render on the card (teamScore)`, [teamScore(hit as never, c.cardHome, NCAAB), teamScore(hit as never, c.cardAway, NCAAB)], ["70", "60"]);
  // pick-game-link: the pick's own /live/<id> link.
  expect(`${c.school}: pick -> game link (liveGameHref)`, liveGameHref([{ id: "g1", homeTeam: c.cardHome, awayTeam: c.cardAway, commenceTime: c.at }], { homeTeam: c.pickHome, awayTeam: c.pickAway, gameTime }, NCAAB), "/live/g1?sport=" + NCAAB);
  // off-board-game: a slip pick keyed to the real card.
  expect(`${c.school}: slip pick -> board game (findBoardGameForPick)`, findBoardGameForPick({ homeTeam: c.pickHome, awayTeam: c.pickAway, gameTime }, [{ id: "g1", homeTeam: c.cardHome, awayTeam: c.cardAway, commenceTime: c.at }], NCAAB, MAX_GAME_TIME_DRIFT_MS)?.id, "g1");
  // final-pick-gate: a pending pick keeps its game's GameResult row, whichever feed spelled the pick.
  const final = { homeTeam: c.pickHome, awayTeam: c.pickAway };
  expect(`${c.school}: ESPN final is kept for the ESPN-spelled pick (finalsWithPicks)`, finalsWithPicks([final], [{ homeTeam: c.pickHome, awayTeam: c.pickAway }], NCAAB).length, 1);
  expect(`${c.school}: ESPN final is kept for an Odds-spelled pick (finalsWithPicks)`, finalsWithPicks([final], [{ homeTeam: c.cardHome, awayTeam: c.cardAway }], NCAAB).length, 1);
  // duplicate-pick-detection: the same bet imported from either feed's spelling is one bet.
  const identity = (home: string, away: string): BetIdentity => ({ homeTeam: home, awayTeam: away, gameTimeMs: gameTime.getTime(), sportKey: NCAAB, period: "FULL_GAME", betType: "SPREAD", category: c.pickedSide === "HOME" ? "FAV_SPREAD" : "DOG_SPREAD", pickedSide: c.pickedSide });
  expect(`${c.school}: ESPN-spelled vs Odds-spelled copy is a duplicate (isSameBet)`, isSameBet(identity(c.pickHome, c.pickAway), identity(c.cardHome, c.cardAway), MAX_GAME_TIME_DRIFT_MS), true);
}

// ---- 7. grading: tonight's pending picks find their finals and grade -------------------------------

// ESPN's final for each game (GameResult.homeTeam/awayTeam are ESPN-spelled). Scores chosen so every
// pick is decided: the dog covers by a clear margin, the favourite wins by more than the line.
const FINALS = [
  { home: 86, away: 80 }, // Duquesne 86, Purdue Fort Wayne 80: PFW +10 WIN
  { home: 90, away: 70 }, // Missouri 90, Cleveland State 70: CSU +27 WIN
  { home: 80, away: 65 }, // Cal Baptist 80, North Florida 65: CBU -10.5 WIN
  { home: 85, away: 70 }, // Georgia Tech 85, Hampton 70: Hampton +14 LOSS (lost by 15)
  { home: 90, away: 71 }, // South Carolina 90, Stetson 71: SC -19.5 LOSS (won by 19)
];
const EXPECTED_GRADE: ("WIN" | "LOSS")[] = ["WIN", "WIN", "WIN", "LOSS", "LOSS"];
CASES.forEach((c, i) => {
  const gameDate = T(c.at);
  const result = { gameDate, homeTeam: c.pickHome, awayTeam: c.pickAway, homeScore: FINALS[i].home, awayScore: FINALS[i].away, gameNumber: null as number | null };
  // The stored pick (ESPN-spelled): the exact branch of matchGameResult.
  const m = matchGameResult([result], { gameTime: gameDate, homeTeam: c.pickHome, awayTeam: c.pickAway, betDetail: c.detail }, NCAAB);
  expect(`${c.school}: the pick finds its final (matchGameResult, exact)`, m?.matchType, "exact");
  const outcome = m
    ? gradePick("SPREAD", c.detail, c.line, m.game.homeTeam, m.game.awayTeam, m.game.homeScore, m.game.awayScore, c.pickedSide)
    : null;
  expect(`${c.school}: grades ${EXPECTED_GRADE[i]} (gradePick)`, outcome, EXPECTED_GRADE[i]);
  // A pick the import resolved from the Odds snapshot (Odds-spelled teams): no exact match; the nickname
  // fallback still reaches the final, as it did before this change. Pinned so the fold cannot disturb it.
  const viaOdds = matchGameResult([result], { gameTime: gameDate, homeTeam: c.cardHome, awayTeam: c.cardAway, betDetail: c.detail }, NCAAB);
  console.log(`INFO: ${c.school}: Odds-spelled pick -> ${viaOdds ? viaOdds.matchType : "no final found"}`);
});

