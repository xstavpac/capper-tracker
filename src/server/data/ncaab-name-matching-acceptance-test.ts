// Proof that a pick stored with ESPN's NCAAB team names finds its game under The Odds API's names -
// the spelling every Live board card carries - and everything downstream of that join.
//
// The bug (2026-11-03): Purdue Fort Wayne +10, Cleveland State +27 and Cal Baptist -10.5 saved fine but
// never appeared on their game cards. The pick has ESPN's "Cleveland State Vikings", the card The Odds
// API's "Cleveland St Vikings"; "Purdue Fort Wayne" is "Fort Wayne", "California Baptist" is "Cal
// Baptist". teamNamesMatch had no NCAAB rows, and the nickname fallback in matchPicksToGame resolves no
// NCAAB team at all, so a differing spelling meant no card. 82 of 366 D1 programs were affected.
//
// The fix is two parts, pinned here: teamNamesMatch / teamNameEndsWith fold the whole word "state" to
// "st" for basketball_ncaab only, and CROSS_SOURCE_TEAM_ALIASES.basketball_ncaab holds whole-name rows for
// the 38 spellings the fold cannot reconcile (generated by scripts/generate-ncaab-odds-aliases.mjs from
// the two feeds' team lists, which are committed as fixtures).
//
// No DB, no network: the participant list is the committed fixture.
// Run with:
//   npx tsx src/server/data/ncaab-name-matching-acceptance-test.ts
// Exits non-zero on any failed assertion.
import { NCAAB_D1_TEAMS } from "@/lib/generated/college-teams.generated";
import { NCAAB_ODDS_PARTICIPANTS } from "@/lib/generated/ncaab-odds-participants.generated";
import { NCAAB_ODDS_ALIAS_ROWS } from "@/lib/generated/ncaab-odds-aliases.generated";
import { normalizeTeamName, teamNamesMatch, teamNameEndsWith, endsWithWholeWords, CROSS_SOURCE_TEAM_ALIASES } from "@/lib/team-name-match";
import { matchPicksToGame, assignPicksToNearestGame } from "./picks";
import { matchGameResult, gradePick, MAX_GAME_TIME_DRIFT_MS } from "./grading";
import { matchScoreToGame, teamScore } from "@/components/live/live-scoreboard-ordering";
import { liveGameHref } from "@/lib/pick-game-link";
import { findBoardGameForPick } from "@/lib/parlay/off-board-game";
import { finalsWithPicks } from "@/lib/final-pick-gate";
import { isSameBet, type BetIdentity } from "@/lib/duplicate-pick-detection";

let failures = 0;
function expect(label: string, actual: unknown, expected: unknown) {
  const pass = JSON.stringify(actual) === JSON.stringify(expected);
  console.log(`${pass ? "PASS" : "FAIL"}: ${label}${pass ? "" : `  (expected ${JSON.stringify(expected)}, got ${JSON.stringify(actual)})`}`);
  if (!pass) failures++;
}

const NCAAB = "basketball_ncaab";
const espn = NCAAB_D1_TEAMS.map((t) => t.name);
const odds = [...NCAAB_ODDS_PARTICIPANTS];
// The one ESPN D1 program with no basketball team on The Odds API's list (see the generator's NO_ODDS_TWIN).
const NO_ODDS_TWIN = new Set(["West Florida Argonauts"]);

// ---- 1. every ESPN D1 name with an Odds API twin matches exactly that twin -------------------------

const twinsOf = (e: string) => odds.filter((o) => teamNamesMatch(e, o, NCAAB));
const noTwin = espn.filter((e) => twinsOf(e).length === 0);
expect("the only ESPN D1 name with no Odds API twin is the known one", noTwin, [...NO_ODDS_TWIN]);
const multi = espn.filter((e) => twinsOf(e).length > 1);
expect("no ESPN name matches more than one Odds API name", multi, []);
expect("ESPN D1 names examined", espn.length, 366);
expect("Odds API participants examined", odds.length, 386);

// ---- 2. no false merges: different schools never match each other ---------------------------------

const falseEspn: string[] = [];
for (let i = 0; i < espn.length; i++) for (let j = i + 1; j < espn.length; j++) if (teamNamesMatch(espn[i], espn[j], NCAAB)) falseEspn.push(espn[i] + " ~ " + espn[j]);
expect("no two distinct ESPN D1 names match each other", falseEspn, []);
const falseOdds: string[] = [];
for (let i = 0; i < odds.length; i++) for (let j = i + 1; j < odds.length; j++) if (teamNamesMatch(odds[i], odds[j], NCAAB)) falseOdds.push(odds[i] + " ~ " + odds[j]);
expect("no two distinct Odds API names match each other", falseOdds, []);
// One Odds API name answers to at most one ESPN school (cross direction).
const claimedBy = new Map<string, string[]>();
for (const e of espn) for (const o of twinsOf(e)) claimedBy.set(o, [...(claimedBy.get(o) ?? []), e]);
expect("no Odds API name is claimed by two ESPN schools", [...claimedBy].filter(([, es]) => es.length > 1), []);
// Every alias row names real teams on both lists (a renamed team fails here, not silently).
expect("every alias row's ESPN name is on the ESPN list", NCAAB_ODDS_ALIAS_ROWS.filter(([e]) => !espn.includes(e)), []);
expect("every alias row's Odds API name is on the participant list", NCAAB_ODDS_ALIAS_ROWS.filter(([, o]) => !odds.includes(o)), []);

// ---- 3. the fold's boundaries ----------------------------------------------------------------------

