  check("the schedule still speaks first: a game out of season keeps NCAAB in", seasonless.sportName, "NCAAB");

  // ---- The capper block ----
  const block = async (lines: string[], near: string[] = [], wide: string[] = near) => (await resolveLines(lines, IN_OVERLAP, near, wide)).picks.map(outcome);
  const OPEN = "PROMPT NCAAF/NCAAB";
  check("no settled college pick -> no signal", await block(["Duke -4.5", "Alabama ML"]), [OPEN, OPEN]);
  check("unanimous NCAAB answers the rest", await block(["Gonzaga -11", "Duke -4.5", "Alabama ML"]), ["NCAAB", "NCAAB", "NCAAB"]);
  check("order on the card doesn't matter", await block(["Duke -4.5", "Gonzaga -11"]), ["NCAAB", "NCAAB"]);
  check("unanimous NCAAF answers the rest", await block(["Clemson under 48.5", "Duke -4.5"]), ["NCAAF", "NCAAF"]);
  check("mixed -> no signal", await block(["Gonzaga -11", "Clemson under 48.5", "Duke -4.5"]), ["NCAAB", "NCAAF", OPEN]);
  check("plausibility is never overridden: a 145.5 total on a football card stays NCAAB", await block(["Clemson under 48.5", "Duke over 145.5"]), ["NCAAF", "NCAAB"]);
  check("plausibility is evidence like any settled pick", await block(["Duke over 145.5", "Alabama ML"]), ["NCAAB", "NCAAB"]);
  check("a pro candidate on the list keeps the question", await block(["Gonzaga -11", "Arizona ML"]), ["NCAAB", "PROMPT NFL/NCAAF/NCAAB"]);
  check("an alias naming two basketball schools keeps the question", await block(["Gonzaga -11", "Loyola ML"]), ["NCAAB", "PROMPT NCAAB/NCAAB/NCAAB"]);
  const twoCappers = await runAmbiguousHierarchy(
    parseCatalog("A\nGonzaga -11\n\nB\nDuke -4.5\n", ["A", "B"], undefined, NCAAB_LISTED_TEAMS).picks,
    {},
    { runScheduleCheck: schedule([]), runWideScheduleCheck: schedule([]), now: IN_OVERLAP }
  );
  check("another capper's card is not this capper's evidence", twoCappers.picks.map(outcome), ["NCAAB", OPEN]);
  const logged = await resolveLines(["Gonzaga -11", "Duke -4.5"], IN_OVERLAP);
  check("logged as capper_block, per pick, not remembered for the key", [logged.logs.map((l) => l.method), logged.decisions], [["capper_block"], {}]);
  const propCard = await resolveLines(["Gonzaga -11", "Duke -4.5"], IN_OVERLAP);
  check("the settled pick the block read is untouched", propCard.picks[0].teamNicknames, ["gonzaga bulldogs"]);

