  check("NBA overlap: 195 keeps both", sports(filterPlausibleCandidates(nbaPair, "TOTAL", 195)), ["NBA", "NCAAB"]);
  check("NBA overlap: 225 is NBA", sports(filterPlausibleCandidates(nbaPair, "TOTAL", 225)), ["NBA"]);
