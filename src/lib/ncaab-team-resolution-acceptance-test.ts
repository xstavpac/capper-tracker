// As production builds it: whatever the NCAAF feed has, then the static list.
const parse = (lines: string[], feed: FeedTeam[] = []) =>
  parseCatalog("Sharp\n" + lines.join("\n") + "\n", ["Sharp"], undefined, [...feed, ...NCAAB_LISTED_TEAMS]);
const legacyParse = (lines: string[], feed?: FeedTeam[]) => parseCatalog("Sharp\n" + lines.join("\n") + "\n", ["Sharp"], undefined, feed);

const schedule = (playing: string[]): ScheduleChecker => async (queries) =>
  Object.fromEntries(queries.map((q) => [q.nickname + "|" + q.sport, playing.includes(q.nickname + "|" + q.sport)]));

async function resolveLines(lines: string[], now: Date, near: string[] = [], wide: string[] = near, feed: FeedTeam[] = []) {
  const log = console.log;
  console.log = () => {};
  const res = await runAmbiguousHierarchy(parse(lines, feed).picks, {}, { runScheduleCheck: schedule(near), runWideScheduleCheck: schedule(wide), now });
  console.log = log;
  return res;
}
const outcome = (p: ParsedPick) => (p.ambiguous ? "PROMPT " + p.ambiguous.map((o) => o.sport).join("/") : p.sportName);

